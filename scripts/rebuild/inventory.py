# everything else that git does not track and models.tsv does not hold is `asis`.

DOWNLOAD_HASHED = True          # the download class is held to recorded sha256s (they are small trees)
LARGE_ASIS = 50_000_000
ALLOWED_LARGE = {f"{R}/ui/release/0.0.0/YourAppName-Linux-0.0.0.AppImage"}     # the Electron build of 2026-09-21


def large_asis(rows):
    return [(path, int(size)) for cls, path, size, _d, _w in rows
            if cls == "asis" and int(size) > LARGE_ASIS and path not in ALLOWED_LARGE]


def match(rel: str, is_dir: bool):
    """(class, why) of the first rule a path matches — a directory is offered with a trailing '/'."""
    probe = rel + "/" if is_dir else rel
    for cls, pattern, why in RULES:
        if pattern.endswith("/"):
            if not is_dir:
                continue
            if pattern.startswith("**/"):
                if os.path.basename(rel) == pattern[3:-1]:
                    return cls, why
            elif probe == pattern:
                return cls, why
        elif is_dir:
            continue
        elif pattern.startswith("**/"):
            if fnmatch.fnmatch(os.path.basename(rel), pattern[3:]):
                return cls, why
        elif pattern.endswith("/**"):
            if rel.startswith(pattern[:-2]):
                return cls, why
        elif fnmatch.fnmatch(rel, pattern) and rel.count("/") == pattern.count("/"):
            return cls, why
    return None, None


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 22), b""):
            h.update(block)
    return h.hexdigest()


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True).stdout


def known_repo_dirs():
    """The work trees the rebuild itself clones: the repo, its submodules, steps_vendors.sh's clones,
    PointDiT's hub code — each with its own submodules. A git clone that some BUILD made (mvs-texturing's
    elibs) is not one of them: its files are archived as they are."""
    dirs = [REPO]
    for line in git(REPO, "config", "--file", ".gitmodules", "--get-regexp", "path").splitlines():
        dirs.append(REPO / line.split()[-1])
    import re
    for name in re.findall(r'^\s*"([A-Za-z0-9._-]+)\|https://', (HERE / "steps_vendors.sh").read_text(), re.M):
        dirs.append(REPO / "vendor" / name)
    dirs.append(REPO / "vendor" / "pointdit" / "third_party" / "dinov3")
    out = []
    for d in dirs:
        if not (d / ".git").exists():
            continue
        out.append(d)
        if d != REPO:
            for line in git(d, "submodule", "status", "--recursive").splitlines():
                parts = line.split()
                if len(parts) >= 2 and (d / parts[1] / ".git").exists():
                    out.append(d / parts[1])
    return out


def git_repos():
    """{absolute dir: the set of the paths it tracks} for every repository the rebuild clones."""
    return {str(d): {os.path.normpath(p) for p in git(d, "ls-files", "-z").split("\0") if p} for d in known_repo_dirs()}


def weights():
    """The absolute paths models.tsv restores: weight files, their links and copies, the cache trees."""
    paths, roots = set(), []
    sys.path.insert(0, str(HERE))
    import models
    for row in models.rows():
        p = models.target(row)
        paths.add(os.path.normpath(str(p)))
        if row["kind"] == "hfcache":                               # (the blob the snapshot link points at)
            try:
                paths.add(os.path.normpath(os.path.realpath(p)))
            except OSError:
                pass
            base = models.cache_base(row)
            if (base / "refs" / "main").exists():
                paths.add(os.path.normpath(str(base / "refs" / "main")))
    return paths


def scan():
    """[(class, path relative to the workspace, bytes, sha256 or '-', note)] for the whole volume."""
    repos = git_repos()
    repo_dirs = sorted(repos, key=len, reverse=True)
    weight_paths = weights()
    rows = []

    def size_of_tree(d: Path):
        files = total = 0
        for root, _dirs, names in os.walk(d):
            for n in names:
                try:
                    total += os.lstat(os.path.join(root, n)).st_size
                    files += 1
                except OSError:
                    pass
        return files, total

    def owner_repo(full: str):
        for r in repo_dirs:
            if full == r or full.startswith(r + os.sep):
                return r
        return None

    for root, dirs, files in os.walk(WORKSPACE):
        rel_root = os.path.relpath(root, WORKSPACE)
        was_empty = not dirs and not files
        keep = []
        for d in sorted(dirs):
            rel = os.path.normpath(os.path.join(rel_root, d))
            full = os.path.join(root, d)
            if os.path.islink(full):
                files.append(d)                                    # (a link to a directory is a file here)
                continue
            if d == ".git" and root in repos:
                continue                                           # (git's own storage of a repo the rebuild clones)
            cls, why = match(rel, True)
            if cls is None:
                keep.append(d)
                continue
            if cls in ("data", "private"):
                n, total = size_of_tree(Path(full))
                rows.append((cls, rel + "/", total, f"{n} files", why))
            else:
                rows.append((cls, rel + "/", 0, "-", why))
        dirs[:] = keep
        if was_empty and rel_root != ".":
            rows.append(("asis", os.path.normpath(rel_root) + "/", 0, "-", "an empty directory"))
        for name in sorted(files):
            rel = os.path.normpath(os.path.join(rel_root, name))
            full = os.path.join(root, name)
            if name == ".git" and root in repos:
                continue                                           # (a submodule's pointer to its storage)
            try:
                st = os.lstat(full)
            except OSError:
                continue
            cls, why = match(rel, False)
            if cls is None:
                repo = owner_repo(full)
                if repo is not None and os.path.relpath(full, repo) in repos[repo]:
                    cls, why = "git", os.path.relpath(repo, WORKSPACE)
                elif os.path.normpath(full) in weight_paths:
                    cls, why = "weight", "models.tsv"
                else:
                    cls, why = "asis", ""
            digest = "-"
            if cls in ("asis", "private") or (cls == "download" and DOWNLOAD_HASHED):
                if os.path.islink(full):
                    digest = "link:" + os.readlink(full)
                elif os.path.isfile(full):
                    digest = sha256_of(Path(full))
            rows.append((cls, rel, st.st_size, digest, why))
    # the git state of every repository: its commit, and the digest of its uncommitted changes
    for repo in sorted(repos):
        head = git(Path(repo), "rev-parse", "HEAD").strip()
        diff = hashlib.sha256(git(Path(repo), "diff", "HEAD").encode()).hexdigest()[:16]
        dirty = "clean" if not git(Path(repo), "status", "--porcelain", "--untracked-files=no").strip() else f"diff {diff}"
        rows.append(("git-head", os.path.relpath(repo, WORKSPACE) + "/", 0, head, dirty))
    return sorted(rows, key=lambda r: (r[1], r[0]))


def write(rows, out: Path) -> None:
    """The inventory as it is committed: a file git tracks is not listed (its repository's commit
    says it all: the `git-head` rows carry the count), and a private file's digest is not written."""
    tracked = {}
    for cls, path, _size, _digest, why in rows:
        if cls == "git":
            tracked[why] = tracked.get(why, 0) + 1
    lines = []
    for cls, path, size, digest, why in rows:
        if cls == "git":
            continue
        if cls == "private":
            digest = digest if digest.endswith("files") else "-"
        if cls == "git-head":
            why = f"{why}; {tracked.get(path.rstrip('/'), 0)} tracked files"
        lines.append("\t".join(str(c) for c in (cls, path, size, digest, why)))
    out.write_text("# class\tpath (relative to the workspace)\tbytes\tsha256 | commit | n files\tnote\n"
                   + "".join(line + "\n" for line in lines))


def read(path: Path):
    return [tuple(line.split("\t")) for line in path.read_text().splitlines() if line and not line.startswith("#")]


def summary(rows) -> None:
    by = {}
    for cls, _p, size, _d, _w in rows:
        n, total = by.get(cls, (0, 0))
        by[cls] = (n + 1, total + int(size))
    for cls in sorted(by):
        n, total = by[cls]
        print(f"  {cls:9s} {n:7d} entries {total / 1e9:9.2f} GB")


# what a comparison holds equal: the class and the content of everything that is NOT data / cache
# (the sessions grow and the logs roll: that is not a change of the software)
def comparable(rows):
    out = {}
    main_repo = REPO_REL + "/"
    kit = f"{REPO_REL}/scripts/rebuild/"
    for cls, path, size, digest, why in rows:
        if cls == "git" or path.startswith(kit) or path == f"{REPO_REL}/server/tests/test_rebuild_kit.py":
            continue                                   # (the repository's commit holds its tracked files; the
                                                       #  kit itself, while uncommitted, is `git status`'s to report)
        if cls in ("data", "cache", "npm", "env"):
            out[path] = (cls, "", "")
        elif cls == "private":
            out[path] = (cls, "", "")                  # (its content is held by the private archive's own list)
        elif cls == "weight":
            out[path] = (cls, str(size), "")
        elif cls == "git-head":
            if path == main_repo:
                continue                               # (this very file is committed in it: `git status` speaks for it)
            out[path] = (cls, digest, str(why).split(";")[0])
        else:
            out[path] = (cls, str(size), digest)
    return out


def check() -> int:
    """The volume against locks/inventory.tsv. A difference in the software (a class that the kit
    restores) fails; the data and the caches are only reported: a pod just rebuilt has no sessions
    until they are copied in."""
    lock = HERE / "locks" / "inventory.tsv"
    if not lock.exists():
        print(f"no {lock}: run scripts/rebuild/capture.sh and commit it")
        return 1
    rows = scan()
    then, now = comparable(read(lock)), comparable(rows)
    soft = ("data", "cache")
    added = sorted(set(now) - set(then))
    gone = sorted(set(then) - set(now))
    changed = sorted(p for p in set(now) & set(then) if now[p] != then[p])
    hard = 0
    for label, paths in (("NEW on the volume", added), ("GONE from the volume", gone), ("CHANGED", changed)):
        shown = 0
        for p in paths:
            cls = (now.get(p) or then.get(p))[0]
            if cls in soft:
                continue
            hard += 1
            if shown < 60:
                print(f"  {label:22s} [{cls}] {p}")
            shown += 1
        if shown > 60:
            print(f"  {label:22s} … and {shown - 60} more")
    missing_data = [p for p in gone if then[p][0] == "data" and p.endswith("/")]
    for p in missing_data:
        print(f"  data not on this volume  {p}  (copied apart: it is not software)")
    for path, size in large_asis(rows):
        print(f"  LARGE FILE WITH NO SOURCE  {size / 1e6:.0f} MB  {path} — a weight? give it a row in models.tsv")
        hard += 1
    print("inventory: the volume is the one the kit describes" if not hard else
          f"inventory: {hard} difference(s) — capture again (scripts/rebuild/capture.sh) and commit the locks")
    return 1 if hard else 0


if __name__ == "__main__":
    argv = sys.argv[1:]
    if argv[:1] == ["scan"]:
        out = Path(argv[argv.index("--out") + 1]) if "--out" in argv else HERE / "locks" / "inventory.tsv"
        rows = scan()
        write(rows, out)
        summary(rows)
        print(f"written: {out}")
        big = large_asis(rows)
        for path, size in big:
            print(f"  LARGE FILE WITH NO SOURCE  {size / 1e6:.0f} MB  {path} — a weight? give it a row in models.tsv")
        sys.exit(1 if big else 0)
    if argv[:1] == ["check"]:
        sys.exit(check())
    if argv[:1] == ["summary"]:
        summary(read(Path(argv[1]) if len(argv) > 1 else HERE / "locks" / "inventory.tsv"))
        sys.exit(0)
    sys.exit(__doc__)
