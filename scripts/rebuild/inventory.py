"""EVERY FILE OF THE VOLUME, and which part of the rebuild puts it back.

    python3 inventory.py scan   [--out FILE]      walk the volume, classify every file, write the inventory
    python3 inventory.py check                    scan and compare with locks/inventory.tsv: what changed
                                                  since the kit was last captured (exit 1 when anything did)
    python3 inventory.py summary [FILE]           the classes, their files and bytes

USER 2026-11-18: "debe quedar exactamente como está ahora … cada cosa que avancemos debemos
actualizarlo para que siempre quede actualizado a la perfección … Revisa pointdit r3d etc etc son
muchos". A list of things to restore can forget one; this cannot: it starts from what IS on the
volume and every file must fall in a class that names how it comes back —

  git        tracked by a git repository (the repo itself, a vendor clone, a submodule): its commit
  weight     a model file of models.tsv (source + sha256)
  env        inside a conda env: the env's locks (conda's packages, pip's wheels) + the env archive
  download   a tree or file fetched again from its pinned source and held to a recorded sha256
  npm        node_modules: `npm ci` from the tracked package-lock.json
  asis       exists nowhere else — compiled on the pod, generated, copied by hand: archived as it is
             (backup.py) and put back byte for byte
  private    the same, but secret or personal (tokens, keys, the users' database): the private archive
  data       the sessions, runs, logs, scratch: not software — listed with their size, copied apart
  cache      rebuilt by whatever uses it (pip's cache, bytecode, derived images)

A file that matches no rule and that nothing else restores is `asis`: it is archived, so it cannot
be lost — but a LARGE one (over LARGE_ASIS bytes) is named as an error until it is given a source
in models.tsv or listed in ALLOWED_LARGE: a new weight must not ride along unnoticed in an archive.
Nothing is left to memory.
Standard library + git; runs with any python ≥ 3.8.
"""
